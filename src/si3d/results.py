"""Per-sample result CSVs under results/<kind>/<method>.csv and the summary tables
results/<kind>_summary.md, which are regenerated from all CSVs on every evaluation run."""
from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

RESULTS = Path("results")

SUMMARY_COLUMNS = {
    "depth": ["abs_rel", "sq_rel", "rmse", "rmse_log", "log10", "d1", "d2", "d3",
              "n_mean_deg", "n_median_deg", "n_p11", "n_p22", "n_p30"],
    "shape": ["accuracy", "completeness", "chamfer", "fscore"],
}
SETTING_COLUMNS = ["align", "space", "gt_frame", "tau"]


def write_csv(kind: str, method: str, rows: list[dict]) -> Path:
    path = RESULTS / kind / f"{method}.csv"
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames: list[str] = []
    for r in rows:
        for k in r:
            if k not in fieldnames:
                fieldnames.append(k)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.6g}" if isinstance(v, float) else v) for k, v in r.items()})
    return path


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    out = []
    for r in rows:
        d = {}
        for k, v in r.items():
            try:
                d[k] = float(v)
            except (TypeError, ValueError):
                d[k] = v
        out.append(d)
    return out


def summarize(kind: str) -> Path:
    cols = SUMMARY_COLUMNS[kind]
    files = sorted((RESULTS / kind).glob("*.csv"))
    lines = [f"# {kind} results", "",
             "Mean over the evaluation subset. Regenerated by scripts/eval_{kind}.py; "
             "per-sample values are in the CSV files next to this table.", ""]
    present = [c for c in cols if any(c in r for p in files for r in read_csv(p)[:1])]
    header = ["method", "n", "settings"] + present
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "|".join(["---"] * len(header)) + "|")
    for p in files:
        rows = read_csv(p)
        if not rows:
            continue
        settings = ", ".join(
            f"{s}={rows[0][s]}" for s in SETTING_COLUMNS if s in rows[0] and rows[0][s] != "")
        cells = [p.stem, str(len(rows)), settings]
        for c in present:
            vals = [r[c] for r in rows if isinstance(r.get(c), float) and np.isfinite(r[c])]
            cells.append(f"{np.mean(vals):.4f}" if vals else "")
        lines.append("| " + " | ".join(cells) + " |")
    out = RESULTS / f"{kind}_summary.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
